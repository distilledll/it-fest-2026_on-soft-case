def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    for pid, files in PACKAGES.items():
        d = OUT / "packages" / pid
        d.mkdir(parents=True)
        for name, text in files.items():
            (d / name).write_text(text, encoding="utf-8")
    with open(OUT / "questions.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["id", "package", "question"])
        for g in GOLD:
            w.writerow([g["id"], g["package"], g["question"]])
    (OUT / "answers_public.json").write_text(json.dumps(GOLD, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(PACKAGES)} закупок, {len(GOLD)} вопросов → {OUT}")


if __name__ == "__main__":
    main()
