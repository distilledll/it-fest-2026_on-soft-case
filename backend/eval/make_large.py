"""Закупка, которая не влезает в окно модели (262k токенов): проект контракта ~2.5 млн символов.

Внутри — не повтор одной фразы, а правдоподобные пункты-«отвлекалки» с теми же словами и другими числами
(«заказчик в течение N рабочих дней рассматривает претензию», «гарантийный срок на расходные материалы…»).
Так проверяется поиск фрагментов, а не только то, что код не падает на большом файле.

Набор не хранится в git (большой) — генерируется:
    python eval/make_large.py            # → eval/large/
"""
import csv
import json
import random
import shutil
from pathlib import Path

OUT = Path(__file__).resolve().parent / "large"
TARGET_CHARS = 2_500_000
NUM = "0000000000026000401"

DISTRACTORS = [
    "Заказчик в течение {n} рабочих дней рассматривает претензию исполнителя и направляет мотивированный ответ.",
    "Заказчик в течение {n} рабочих дней со дня получения счёта осуществляет его проверку.",
    "Исполнитель в течение {n} рабочих дней устраняет замечания, выявленные при эксплуатации системы.",
    "Гарантийный срок на расходные материалы, поставляемые в рамках сопровождения, составляет {n} месяцев.",
    "Гарантийный срок на документацию пользователя составляет {n} месяцев с даты её передачи.",
    "Пени начисляются за каждый день просрочки в размере одной трёхсотой ключевой ставки.",
    "Специалисты исполнителя обязаны соблюдать правила внутреннего распорядка заказчика.",
    "Исполнитель направляет заказчику отчёт об оказанных услугах не позднее {n} числа месяца, следующего за отчётным.",
    "Срок рассмотрения запроса на изменение функциональности составляет {n} календарных дней.",
    "Размер штрафа за нарушение порядка представления отчётности определяется правилами Правительства Российской Федерации.",
    "Стороны в течение {n} календарных дней согласовывают план-график работ на следующий этап.",
    "Обеспечение исполнения контракта возвращается исполнителю в течение {n} дней с даты исполнения обязательств.",
]

KEY = {
    "warranty": "Гарантийный срок на результаты работ составляет 30 (тридцать) месяцев с даты подписания документа о приёмке.",
    "accept": "Заказчик в течение 12 (двенадцати) рабочих дней со дня получения документа о приёмке проверяет результаты работ.",
    "fine": "Размер штрафа за каждый факт неисполнения исполнителем обязательства, не имеющего стоимостного выражения, "
            "составляет 5 000,00 рублей.",
}


def big_contract() -> str:
    rnd = random.Random(42)
    lines = [f"ПРОЕКТ КОНТРАКТА № {NUM}\n(вымышленная закупка для проверки работы с большими документами)\n"]
    keys_at = {int(TARGET_CHARS * f): k for f, k in ((0.37, "warranty"), (0.58, "accept"), (0.81, "fine"))}
    size, clause = 0, 1
    pending = sorted(keys_at.items())
    while size < TARGET_CHARS:
        part = []
        for _ in range(rnd.randint(2, 4)):
            part.append(rnd.choice(DISTRACTORS).format(n=rnd.choice([3, 5, 7, 10, 14, 15, 20, 24, 36])))
        if pending and size >= pending[0][0]:
            part.insert(rnd.randint(0, len(part)), KEY[pending.pop(0)[1]])
        line = f"{clause // 10 + 1}.{clause % 10 + 1}. " + " ".join(part)
        lines.append(line)
        size += len(line) + 1
        clause += 1
    assert not pending
    return "\n".join(lines) + "\n"


NOTICE = (f"ИЗВЕЩЕНИЕ ОБ ОСУЩЕСТВЛЕНИИ ЗАКУПКИ № {NUM}\n(вымышленная закупка)\n\n"
          "Объект закупки: создание и сопровождение региональной системы мониторинга.\n"
          "Начальная (максимальная) цена контракта: 7 700 000,00 руб.\n\n"
          "1. Обеспечение исполнения контракта устанавливается в размере 10 % от цены контракта.\n"
          "2. Дата и время окончания срока подачи заявок: 10.12.2026 10:00 (время московское).\n")

GOLD = [
    ("L01-01", "Какой гарантийный срок на результаты работ, в месяцах?", "num", [30.0], "большой файл (> окна)",
     "04_proekt_kontrakta.txt", "30 (тридцать) месяцев"),
    ("L01-02", "За сколько рабочих дней заказчик проверяет результаты работ после получения документа о приёмке?",
     "num", [12.0], "большой файл (> окна)", "04_proekt_kontrakta.txt", "12 (двенадцати) рабочих дней"),
    ("L01-03", "Какой размер штрафа за каждый факт неисполнения обязательства, не имеющего стоимостного выражения, в рублях?",
     "num", [5000.0], "большой файл (> окна)", "04_proekt_kontrakta.txt", "составляет 5 000,00 рублей"),
    ("L01-04", "Какая начальная (максимальная) цена контракта, в рублях?", "num", [7700000.0], "факт",
     "01_izveshchenie.txt", "Начальная (максимальная) цена контракта: 7 700 000,00 руб"),
    ("L01-05", "Сколько рублей составит обеспечение исполнения контракта, если контракт заключат по НМЦК?", "num",
     [770000.0], "расчёт", "01_izveshchenie.txt", "10 % от цены контракта"),
    ("L01-06", "Сколько специалистов исполнитель обязан привлечь к работам?", "absent", [],
     "большой файл (> окна): нет в документах", "", ""),
]


def main():
    if OUT.exists():
        shutil.rmtree(OUT)
    d = OUT / "packages" / "L01"
    d.mkdir(parents=True)
    contract = big_contract()
    (d / "01_izveshchenie.txt").write_text(NOTICE, encoding="utf-8")
    (d / "04_proekt_kontrakta.txt").write_text(contract, encoding="utf-8")
    files = {"01_izveshchenie.txt": NOTICE, "04_proekt_kontrakta.txt": contract}
    gold = []
    for qid, question, kind, exp, type_, file, quote in GOLD:
        status = "нет в документах" if kind == "absent" else "ответ"
        if status == "ответ":
            assert files[file].count(quote) == 1, f"{qid}: цитата должна встречаться ровно один раз"
        gold.append({"id": qid, "package": "L01", "source": "L01", "key": "", "question": question, "kind": kind,
                     "expected": exp, "type": type_, "status": status, "file": file, "quote": quote})
    with open(OUT / "questions.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["id", "package", "question"])
        for g in gold:
            w.writerow([g["id"], g["package"], g["question"]])
    (OUT / "answers_public.json").write_text(json.dumps(gold, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"проект контракта: {len(contract):,} символов → {OUT}")


if __name__ == "__main__":
    main()
