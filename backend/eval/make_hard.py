def filler(n: int, seed: int = 0) -> str:
    return " ".join(FILLER[(seed + i) % len(FILLER)] for i in range(n))


def section(title: str, items: list[str], seed: int = 0) -> str:
    lines = [title]
    for i, it in enumerate(items, 1):
        lines.append(f"{i}. {it} {filler(1, seed + i)}")
    return "\n".join(lines)


def doc(title: str, number: str, *sections: str) -> str:
    head = f"{title} № {number}\n(вымышленная закупка для проверки устойчивости)\n\n"
    return head + "\n\n".join(sections) + "\n"


PACKAGES: dict[str, dict] = {}
GOLD: list[dict] = []


def pkg(pid: str, files: dict[str, str], encoding: str = "utf-8"):
    PACKAGES[pid] = {"files": files, "encoding": encoding}


def q(pid: str, n: int, question: str, kind: str, expected, type_: str, status: str = "ответ",
      file: str = "", quote: str = ""):
    if status == "ответ" or status == "расхождение":
        text = PACKAGES[pid]["files"][file]
        assert quote and quote in text, f"{pid}-{n:02d}: цитаты нет в {file}: {quote!r}"
    GOLD.append({"id": f"{pid}-{n:02d}", "package": pid, "source": pid, "key": "", "question": question,
                 "kind": kind, "expected": expected, "type": type_, "status": status, "file": file, "quote": quote})


