def messages(question, files, documents, instruction="", extra=None):
    payload = dict(question=question, files=files, documents=documents)
    if extra is not None:
        payload['application_context'] = extra
    return [{"role": "system", "content": SYSTEM + ("\n" + instruction if instruction else "")},
            {"role": "user", "content": json.dumps(payload, ensure_ascii=False)}]


PROMPT_VERSION = hashlib.sha256((SYSTEM + SCAN + SYNTHESIS).encode()).hexdigest()
