"""Числа прописью → цифры: «пятидесяти тысяч рублей» → 50000, «ста двадцати» → 120.
Нужен критику чисел: в документах суммы и сроки бывают только словами, а ответ — цифрами."""
import re

_U = {}
for value, forms in {
    1: "один одна одно одного одной одному одним", 2: "два две двух двум двумя", 3: "три трех трём трем тремя трёх",
    4: "четыре четырех четырёх четырем четырём", 5: "пять пяти пятью", 6: "шесть шести", 7: "семь семи",
    8: "восемь восьми", 9: "девять девяти",
    10: "десять десяти", 11: "одиннадцать одиннадцати", 12: "двенадцать двенадцати", 13: "тринадцать тринадцати",
    14: "четырнадцать четырнадцати", 15: "пятнадцать пятнадцати", 16: "шестнадцать шестнадцати",
    17: "семнадцать семнадцати", 18: "восемнадцать восемнадцати", 19: "девятнадцать девятнадцати",
    20: "двадцать двадцати", 30: "тридцать тридцати", 40: "сорок сорока", 50: "пятьдесят пятидесяти",
    60: "шестьдесят шестидесяти", 70: "семьдесят семидесяти", 80: "восемьдесят восьмидесяти",
    90: "девяносто девяноста",
    100: "сто ста", 200: "двести двухсот", 300: "триста трехсот трёхсот", 400: "четыреста четырехсот четырёхсот",
    500: "пятьсот пятисот", 600: "шестьсот шестисот", 700: "семьсот семисот", 800: "восемьсот восьмисот",
    900: "девятьсот девятисот",
}.items():
    for f in forms.split():
        _U[f] = value

_SCALE = {}
for value, forms in {1000: "тысяча тысячи тысяч тысячу тысячей", 10**6: "миллион миллиона миллионов миллиону",
                     10**9: "миллиард миллиарда миллиардов"}.items():
    for f in forms.split():
        _SCALE[f] = value

_TOKEN = re.compile(r"[а-яё]+|\d+(?:[.,]\d+)?", re.I)


def word_numbers(text: str) -> list[float]:
    """Все числа, записанные словами (в т.ч. «1,5 миллиона» — смешанная запись)."""
    out, total, group, active = [], 0.0, 0.0, False

    def flush():
        nonlocal total, group, active
        if active:
            out.append(total + group)
        total, group, active = 0.0, 0.0, False

    for tok in _TOKEN.findall((text or "").lower()):
        if tok in _U:
            group += _U[tok]
            active = True
        elif tok in _SCALE:
            total += (group or 1) * _SCALE[tok]
            group, active = 0.0, True
        elif tok[0].isdigit() and not active:
            flush()
            group, active = float(tok.replace(",", ".")), True   # «1,5 миллиона»
        else:
            flush()
    flush()
    return out
